// Личные данные (Wi-Fi, адрес сервера, OTA-пароль) лежат в secrets.h.
// Он в .gitignore; образец — secrets.example.h.
#include "secrets.h"

#define HOSTNAME        "esp32-voice"

// --- Сервер ассистента ---
#define SERVER_PORT     8000
#define SERVER_PATH     "/ws"

// ============================================================
//  ПИНЫ (ESP32-S3-DevKitC-1)
// ============================================================

// INMP441 (микрофон)
#define PIN_MIC_SCK     4    // SCK  / BCLK
#define PIN_MIC_WS      5    // WS   / LRCLK
#define PIN_MIC_SD      6    // SD   / DATA -> DIN ESP32

// MAX98357A (усилитель + динамик)
#define PIN_SPK_BCLK    15   // BCLK
#define PIN_SPK_LRC     16   // LRC  / LRCLK
#define PIN_SPK_DIN     17   // DIN  / DATA

// Кнопка BOOT на DevKitC-1 (GPIO0)
#define PIN_BUTTON      0

// ============================================================
//  АУДИО
// ============================================================

// Сервер ждёт 16 кГц моно PCM int16 — не менять.
#define MIC_SAMPLE_RATE   16000

// Piper (ru_RU-denis-medium) отдаёт 22050 Гц — не менять.
#define SPK_SAMPLE_RATE   22050

// Цифровое усиление микрофона (INMP441 довольно тихий).
// 4 было тихо; 8 — заметно громче. Если сервер увидит clip > 1-2%,
// снизить до 6.
#define MIC_GAIN          8

// ============================================================
//  VAD (детектор речи)
// ============================================================

// VAD адаптивный: фон комнаты измеряется до писка, первые 400 мс записи
// не анализируются (хвост писка). Дальше порог речи/тишины считается от
// фона, а эти значения — нижняя граница.
#define VAD_START_RMS     500
#define VAD_SILENCE_RMS   300
// Пауза после речи, после которой запись завершается и уходит на сервер.
// 350 мс оказалось слишком мало — резало на естественных паузах между
// словами. 500 мс — ещё «сразу», но уже не рубит фразу.
#define VAD_SILENCE_MS    500
// Почти полная тишина (ниже фона) — режем чуть быстрее.
#define VAD_SILENCE_FAST_MS  300
// Не даём VAD завершить запись в первые 500 мс после начала речи:
// иначе короткое слово/пауза обрывает всё сразу.
#define VAD_MIN_SPEECH_MS 500
#define MAX_RECORD_MS     12000
#define VAD_START_TIMEOUT 6000
// После ответа ассистента слушаем продолжение диалога без кнопки.
// Если за это время речи нет — возвращаемся в idle.
#define FOLLOWUP_LISTEN_TIMEOUT_MS 5000

// ============================================================
//  СОН (экономия батареи)
// ============================================================

#define IDLE_SLEEP_MS 120000

// ============================================================
//  ВРЕМЯ ОТВЕТА СЕРВЕРА
// ============================================================

#define RESPONSE_TIMEOUT_MS 90000
